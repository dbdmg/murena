"""Derive imperfect-user variants of the nested 48-variant benchmark.

Deterministic, no model calls. For every scenario with k >= 1 it writes up to
two variants that differ from the cooperative scenario in exactly one
simulated answer:

* ``optout``: the first omitted *preference* dimension (Cb, Ce or Cp, in the
  scenario's omission order) is answered with an explicit "no requirement".
  The expected final state of that dimension becomes NOT_REQUESTED. Scenarios
  whose omissions are only D and/or L get no opt-out variant.
* ``vague``: the first omitted dimension first receives a vague reply, then
  the exact fragment if the system asks again. The expected final mapping is
  unchanged (SPECIFIED).

Initial queries, one-shot and oracle queries are copied unchanged, so the
oracle units are identical to the cooperative benchmark's.

Usage (repository root):
    uv run python backend/experiments/data/scenarios_v3/derive_imperfect_user.py
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
PREFERENCE_DIMENSIONS = ("Cb", "Ce", "Cp")
OPT_OUT_ANSWERS = {
    # Covers the whole Cb dimension (size, capacity and structural features);
    # a narrower wording was read as a partial opt-out in the pre-fix run.
    "Cb": "I have no requirement on building size, capacity or structural features.",
    "Ce": "I have no requirement on the energy class.",
    "Cp": "I have no requirement on nearby services.",
}
VAGUE_ANSWER = "It depends; something suitable for the project, I guess."


def derive(scenarios: list[dict]) -> list[dict]:
    derived: list[dict] = []
    for scenario in scenarios:
        missing = scenario.get("expected_initial_missing") or []
        if not missing:
            continue
        preference = next((d for d in missing if d in PREFERENCE_DIMENSIONS), None)
        if preference is not None:
            variant = json.loads(json.dumps(scenario))
            variant["id"] = f"{scenario['id']}_optout"
            variant["name"] = f"{scenario['name']}; opt-out on {preference}"
            variant["tags"] = [*scenario.get("tags", []), "imperfect_user", "optout"]
            variant["clarifications"][preference] = OPT_OUT_ANSWERS[preference]
            variant["expected_mapping"][preference] = "NOT_REQUESTED"
            variant["imperfect_user"] = {"profile": "optout", "dimension": preference}
            derived.append(variant)
        target = missing[0]
        variant = json.loads(json.dumps(scenario))
        variant["id"] = f"{scenario['id']}_vague"
        variant["name"] = f"{scenario['name']}; vague first answer on {target}"
        variant["tags"] = [*scenario.get("tags", []), "imperfect_user", "vague"]
        variant["clarifications"][target] = [VAGUE_ANSWER, scenario["clarifications"][target]]
        variant["imperfect_user"] = {"profile": "vague", "dimension": target}
        derived.append(variant)
    return derived


def validate(source: list[dict], derived: list[dict]) -> None:
    by_id = {s["id"]: s for s in source}
    ids = [v["id"] for v in derived]
    assert len(ids) == len(set(ids)), "duplicate variant IDs"
    for variant in derived:
        base = by_id[variant["id"].rsplit("_", 1)[0]]
        profile, dim = variant["imperfect_user"]["profile"], variant["imperfect_user"]["dimension"]
        changed = [d for d in base["clarifications"] if base["clarifications"][d] != variant["clarifications"][d]]
        assert changed == [dim], (variant["id"], changed)
        assert dim in base["expected_initial_missing"], variant["id"]
        for field in ("initial_query", "one_shot_query", "oracle_query", "base_case_id", "expected_initial_missing"):
            assert variant[field] == base[field], (variant["id"], field)
        if profile == "optout":
            assert dim in PREFERENCE_DIMENSIONS and variant["expected_mapping"][dim] == "NOT_REQUESTED"
        else:
            assert variant["expected_mapping"] == base["expected_mapping"]
            assert variant["clarifications"][dim] == [VAGUE_ANSWER, base["clarifications"][dim]]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=HERE / "nested48_from_4a7c882.yaml")
    parser.add_argument("--output", type=Path, default=HERE / "imperfect_user.yaml")
    args = parser.parse_args()
    raw = args.source.read_bytes()
    source = yaml.safe_load(raw)
    derived = derive(source)
    validate(source, derived)
    header = (
        "# Generated by derive_imperfect_user.py; do not edit by hand.\n"
        f"# source: {args.source.name} sha256={hashlib.sha256(raw).hexdigest()}\n"
    )
    args.output.write_text(
        header + yaml.safe_dump(derived, sort_keys=False, allow_unicode=True, width=1000),
        encoding="utf-8",
    )
    counts = {p: sum(v["imperfect_user"]["profile"] == p for v in derived) for p in ("optout", "vague")}
    print(f"Wrote {len(derived)} variants {counts} to {args.output}")


if __name__ == "__main__":
    main()
